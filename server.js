// --- AUTOMATIC TTS WATCHER ---
// Scans /tmp/openclaw for new .mp3 files and broadcasts them automatically.
// This allows the dashboard to "pull" new voice responses without explicit API calls.
let lastPlayedFile = null;
let lastPlayedTime = Date.now();
let lastAgentMessageTime = 0; // Tracks when a chat message was sent to OpenClaw
let pendingFiles = {}; // Track files being written: { path: { size, mtimeMs } }

function scanForNewAudio() {
    const ttsDir = '/tmp/openclaw';
    if (!fs.existsSync(ttsDir)) return;

    // If an agent message was just sent, skip the watcher for a few seconds 
    // to give the dashboard's immediate stream priority.
    // Increased to 60s to account for slow ElevenLabs generations.
    if (Date.now() - lastAgentMessageTime < 60000) {
        return;
    }

    try {
        const subdirs = fs.readdirSync(ttsDir).filter(d => d.startsWith('tts-') && d !== 'tts-dashboard' && d !== 'tts-cache');
        let currentFiles = {};

        for (const subdir of subdirs) {
            const fullSubdir = path.join(ttsDir, subdir);
            const files = fs.readdirSync(fullSubdir).filter(f => f.endsWith('.mp3'));
            
            for (const file of files) {
                const filePath = path.join(fullSubdir, file);
                const stats = fs.statSync(filePath);
                const relPath = `${subdir}/${file}`;
                
                // Only consider files newer than the last played time
                if (stats.mtimeMs > lastPlayedTime && relPath !== lastPlayedFile) {
                    currentFiles[relPath] = {
                        size: stats.size,
                        mtimeMs: stats.mtimeMs
                    };
                }
            }
        }

        // Check pending files to see if their size has stabilized
        for (const [relPath, data] of Object.entries(currentFiles)) {
            if (pendingFiles[relPath]) {
                // If size hasn't changed since last tick, increment stable ticks
                if (pendingFiles[relPath].size === data.size && data.size > 0) {
                    const ticks = (pendingFiles[relPath].stableTicks || 0) + 1;
                    
                    // Require size to be stable for at least 4 ticks (4 seconds)
                    if (ticks >= 4) {
                        console.log(`[TTS Watcher] Audio fully written after ${ticks}s, broadcasting: ${relPath}`);
                        lastPlayedFile = relPath;
                        lastPlayedTime = data.mtimeMs;
                        
                        io.emit('ttsPlay', { 
                            // Add cache buster to prevent browser from caching a potentially incomplete file
                            url: `/audio/tts/${relPath}?t=${Date.now()}`,
                            text: 'Auto-detected new voice file'
                        });
                        
                        // Clear pending after playing to avoid re-triggering
                        delete pendingFiles[relPath];
                        break; // Only play one new file per tick to avoid overlap
                    } else {
                        pendingFiles[relPath].stableTicks = ticks;
                    }
                } else {
                    // Size changed, reset stable ticks and update size
                    pendingFiles[relPath] = { ...data, stableTicks: 0 };
                }
            } else {
                // New file detected, add to pending list
                pendingFiles[relPath] = { ...data, stableTicks: 0 };
            }
        }
        
        // Cleanup old pending files that are no longer in currentFiles
        for (const relPath in pendingFiles) {
            if (!currentFiles[relPath]) {
                delete pendingFiles[relPath];
            }
        }
    } catch (err) {
        // Silent fail for directory read errors
    }
}

// Scan frequently to quickly catch when size stabilizes
setInterval(scanForNewAudio, 1000);

// --- TTS BROADCAST ENDPOINT ---
// Allows OpenClaw or other scripts to trigger audio playback on all connected dashboards
app.post('/api/tts/broadcast', (req, res) => {
    const { filename, text } = req.body;
    console.log(`[TTS Broadcast] Received: filename="${filename}", text="${text}"`);
    
    if (!filename) {
        return res.status(400).json({ error: 'Filename is required' });
    }
    
    // If an agent message was recently sent and this broadcast has no text,
    // it's likely a redundant duplicate from the agent CLI. Skip it.
    // Increased to 60s to match watcher.
    if (Date.now() - lastAgentMessageTime < 60000 && !text) {
        console.log(`[TTS Broadcast] Ignoring text-less broadcast during active agent session to prevent stutter.`);
        return res.json({ success: true, message: 'Broadcast ignored (redundant during active chat)' });
    }

    // Broadcast the event to all connected Socket.io clients
    req.io.emit('ttsPlay', { 
        url: filename.startsWith('http') ? filename : `/audio/tts/${filename}`,
        text: text || ''
    });

    // Update the watcher state to prevent re-playing the same file if it's in /tmp/openclaw
    lastPlayedFile = filename;
    lastPlayedTime = Date.now();
    
    res.json({ success: true, message: 'TTS playback broadcasted' });
});

