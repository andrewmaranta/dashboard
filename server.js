async function generateOpenAITTS(text, filePath) {
    const OPENAI_API_KEY = process.env.OPENAI_API_KEY;
    const VOICE = "marin"; // User requested Marin voice (2026 model)

    return new Promise((resolve) => {
        if (!OPENAI_API_KEY) {
            console.warn(`[TTS] No OPENAI_API_KEY found in .env. Skipping OpenAI...`);
            return resolve(false);
        }

        console.log(`[TTS] Attempting OpenAI generation (Voice: ${VOICE})...`);

        const postData = JSON.stringify({
            model: "gpt-4o-mini-tts", // gpt-4o-mini-tts supports marin on v1/audio/speech
            voice: VOICE,
            input: text
        });

        const options = {
            hostname: 'api.openai.com',
            path: '/v1/audio/speech',
            method: 'POST',
            headers: {
                'Authorization': `Bearer ${OPENAI_API_KEY}`,
                'Content-Type': 'application/json',
                'Content-Length': Buffer.byteLength(postData)
            }
        };

        const req = https.request(options, (res) => {
            if (res.statusCode === 200) {
                const fileStream = fs.createWriteStream(filePath);
                res.pipe(fileStream);
                fileStream.on('finish', () => {
                    console.log(`[TTS] OpenAI success: ${filePath}`);
                    resolve(true);
                });
            } else {
                let errorBody = '';
                res.on('data', (chunk) => { errorBody += chunk; });
                res.on('end', () => {
                    console.error(`[TTS] OpenAI failed (Status: ${res.statusCode}). Body: ${errorBody}.`);
                    resolve(false);
                });
            }
        });

        req.on('error', (e) => {
            console.error(`[TTS] OpenAI request error: ${e.message}.`);
            resolve(false);
        });

        req.write(postData);
        req.end();
    });
}

