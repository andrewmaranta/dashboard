async function generateEdgeTTS(text, filePath) {
    console.log(`[TTS] Using Microsoft Edge...`);
    const ttsCmd = `/home/maranta/.npm-global/lib/node_modules/openclaw/node_modules/.bin/node-edge-tts --voice "en-AU-NatashaNeural" --rate "+20%" --text ${JSON.stringify(text)} --filepath "${filePath}"`;
    return new Promise((resolve) => {
        execShell(ttsCmd, (ttsErr) => {
            if (ttsErr) {
                console.error(`[TTS] Edge failed: ${ttsErr.message}`);
                resolve(false);
            } else {
                console.log(`[TTS] Edge success: ${filePath}`);
                resolve(true);
            }
        });
    });
}

// Helper to generate TTS with fallback
async function generateTTSWithFallback(text, filePath, preferredEngine = 'openai', voiceId = null) {
    let success = false;

    if (preferredEngine === 'openai') {
        success = await generateOpenAITTS(text, filePath);
    } else if (preferredEngine === 'elevenlabs') {
        success = await generateElevenLabsTTS(text, filePath, voiceId);
    } else if (preferredEngine === 'edge') {
        success = await generateEdgeTTS(text, filePath);
    }

    // Fallback if preferred failed or wasn't specified
    if (!success && preferredEngine !== 'openai') {
        success = await generateOpenAITTS(text, filePath);
    }
    
    if (!success && preferredEngine !== 'elevenlabs') {
        // Only try ElevenLabs as fallback if we have a key
        if (process.env.ELEVEN_LABS_API_KEY) {
            success = await generateElevenLabsTTS(text, filePath, voiceId);
        }
    }

    if (!success) {
        success = await generateEdgeTTS(text, filePath);
    }

    return success;
}

// --- STREAMING TTS ENDPOINT ---
app.get('/api/tts/stream', async (req, res) => {
    const { text, engine = 'openai', voiceId } = req.query;
    if (!text) return res.status(400).send('Text is required');

    const OPENAI_API_KEY = process.env.OPENAI_API_KEY;
    const ELEVEN_LABS_API_KEY = process.env.ELEVEN_LABS_API_KEY;
    const DEFAULT_ELEVEN_LABS_VOICE_ID = process.env.ELEVEN_LABS_VOICE_ID || "MClEFoImJXBTgLwdLI5n";
    const selectedVoiceId = (engine === 'elevenlabs' && voiceId) ? voiceId : DEFAULT_ELEVEN_LABS_VOICE_ID;

    // Cache logic to prevent duplicate API calls for the exact same message
    const cacheKey = crypto.createHash('md5').update(`${text}_${engine}_${selectedVoiceId}`).digest('hex');
    const cacheDir = '/tmp/openclaw/tts-cache';
    const cacheFile = path.join(cacheDir, `${cacheKey}.mp3`);

    if (!fs.existsSync(cacheDir)) {
        fs.mkdirSync(cacheDir, { recursive: true });
    }

    if (fs.existsSync(cacheFile)) {
        console.log(`[TTS Stream] Serving cached audio for replay: ${cacheKey}`);
        res.setHeader('Content-Type', 'audio/mpeg');
        return fs.createReadStream(cacheFile).pipe(res);
    }

    if (engine === 'openai' && OPENAI_API_KEY) {
        console.log(`[TTS Stream] Streaming from OpenAI (Marin)...`);
        const postData = JSON.stringify({
            model: "gpt-4o-mini-tts",
            voice: "marin",
            input: text
        });

        const options = {
            hostname: 'api.openai.com',
            path: '/v1/audio/speech',
            method: 'POST',
            headers: {
                'Authorization': `Bearer ${OPENAI_API_KEY}`,
                'Content-Type': 'application/json'
            }
        };

        const aiReq = https.request(options, (aiRes) => {
            res.setHeader('Content-Type', 'audio/mpeg');
            // Save to cache while streaming to client
            const fileStream = fs.createWriteStream(cacheFile);
            aiRes.pipe(fileStream);
            aiRes.pipe(res);
        });

        aiReq.on('error', (e) => {
            console.error(`[TTS Stream] OpenAI error: ${e.message}`);
            res.status(500).send('Streaming failed');
        });

        aiReq.write(postData);
        aiReq.end();
    } else if (engine === 'elevenlabs' && ELEVEN_LABS_API_KEY) {
        console.log(`[TTS Stream] Streaming from ElevenLabs (${selectedVoiceId})...`);
        const postData = JSON.stringify({
            text: text,
            model_id: "eleven_v3",
            voice_settings: {
                stability: 0.5,
                similarity_boost: 0.75
            }
        });

        const options = {
            hostname: 'api.elevenlabs.io',
            path: `/v1/text-to-speech/${selectedVoiceId}/stream`,
            method: 'POST',
            headers: {
                'xi-api-key': ELEVEN_LABS_API_KEY,
                'Content-Type': 'application/json'
            }
        };

        const aiReq = https.request(options, (aiRes) => {
            if (aiRes.statusCode !== 200) {
                console.error(`[TTS Stream] ElevenLabs error status: ${aiRes.statusCode}`);
                let errorData = '';
                aiRes.on('data', d => errorData += d);
                aiRes.on('end', () => console.error(`[TTS Stream] ElevenLabs error body: ${errorData}`));
                return res.status(aiRes.statusCode).send('ElevenLabs streaming failed');
            }
            res.setHeader('Content-Type', 'audio/mpeg');
            // Save to cache while streaming to client
            const fileStream = fs.createWriteStream(cacheFile);
            aiRes.pipe(fileStream);
            aiRes.pipe(res);
        });

        aiReq.on('error', (e) => {
            console.error(`[TTS Stream] ElevenLabs request error: ${e.message}`);
            res.status(500).send('Streaming failed');
        });

        aiReq.write(postData);
        aiReq.end();
    } else {
        // Fallback to pre-generated or edge? For now, we focus on OpenAI streaming
        res.status(400).send('Streaming only supported for OpenAI currently');
    }
});

app.post('/api/openclaw/message', (req, res) => {
    const { message, ttsEngine = 'openai', voiceId } = req.body;
    
    // Mute the watcher briefly while we process this chat message
    lastAgentMessageTime = Date.now();

    if (!message || typeof message !== 'string') {
        return res.status(400).json({ error: 'Message text is required' });
    }

    console.log(`[OpenClaw] Sending message: "${message}" (TTS Engine: ${ttsEngine}, Voice: ${voiceId || 'default'})`);
    
    // Use execFile instead of exec to avoid shell injection and quoting issues
    const args = ['agent', '--session-id', 'personal', '--message', message, '--json'];
    
    execFile('/home/maranta/.npm-global/bin/openclaw', args, (error, stdout, stderr) => {
        if (error) {
            console.error(`[OpenClaw] Error executing command: ${error.message}`);
            return res.status(500).json({ error: 'Failed to communicate with OpenClaw' });
        }
        
        try {
            // Try to parse the JSON response from OpenClaw
            // Extract the largest possible JSON block (from first { to last })
            const firstBrace = stdout.indexOf('{');
            const lastBrace = stdout.lastIndexOf('}');
            
            let responseData = null;
            if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
                const jsonStr = stdout.substring(firstBrace, lastBrace + 1);
                try {
                    responseData = JSON.parse(jsonStr);
                    console.log(`[OpenClaw] Successfully parsed JSON response (${jsonStr.length} chars)`);
                } catch (parseErr) {
                    console.error(`[OpenClaw] JSON Parse error: ${parseErr.message}`);
                    // If full block fails, try matching smaller blocks as a fallback
                    const jsonMatches = stdout.match(/\{[\s\S]*?\}/g) || [];
                    for (const match of jsonMatches) {
                        try {
                            const parsed = JSON.parse(match);
                            if (parsed.result || parsed.payloads || parsed.text) {
                                responseData = parsed;
                                break;
                            }
                        } catch (e) {}
                    }
                }
            }
            
            if (!responseData) {
                responseData = { text: stdout.trim() || stderr.trim() || "Ruby processed the message but returned no output." };
            }
            
            let agentText = null;
            
            // Extract and concatenate all text payloads returned by the agent
            if (responseData.result && responseData.result.payloads) {
                const textParts = responseData.result.payloads
                    .filter(p => p.text)
                    .map(p => p.text);
                
                if (textParts.length > 0) {
                    agentText = textParts.join('\n\n');
                    console.log(`[OpenClaw] Agent replied with ${textParts.length} text parts.`);
                }
            } else if (responseData.payloads) {
                // Handle direct payloads (non-result wrapped)
                const textParts = responseData.payloads
                    .filter(p => p.text)
                    .map(p => p.text);
                
                if (textParts.length > 0) {
                    agentText = textParts.join('\n\n');
                }
            } else if (responseData.text) {
                agentText = responseData.text; 
            } else if (typeof responseData === 'string') {
                agentText = responseData;
            }

            if (!agentText) {
                console.log(`[OpenClaw] Agent replied with empty/unrecognized format. Raw stdout: ${stdout.substring(0, 200)}...`);
                agentText = "Ruby processed your request but the response format was unrecognized.";
            }
            
            // --- STREAMING TRIGER ---
            // If the agent replied with text, tell the client to stream the audio IMMEDIATELY
            if (agentText && agentText !== "Ruby processed your request but the response format was unrecognized.") {
                // Aggressively clean the text for natural speech synthesis
                let cleanText = agentText
                    .replace(/\*\*/g, '')          
                    .replace(/\*/g, '')            
                    .replace(/__/g, '')            
                    .replace(/_/g, '')             
                    .replace(/`/g, '')             
                    .replace(/^-\s/gm, '')         
                    .replace(/#/g, '')             
                    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1') 
                    .replace(/\n/g, '. ')          
                    .replace(/\s+/g, ' ')          
                    .trim();

                // If NOT using ElevenLabs, strip the [tag] speech markers so they aren't spoken literally
                if (ttsEngine !== 'elevenlabs') {
                    cleanText = cleanText.replace(/\[[a-zA-Z\s]+\]/g, '');
                }

                console.log(`[OpenClaw] Triggering immediate TTS stream for response...`);
                io.emit('ttsPlay', { 
                    url: `/api/tts/stream?text=${encodeURIComponent(cleanText)}&engine=${ttsEngine}&voiceId=${voiceId || ''}&t=${Date.now()}`,
                    text: agentText // Send original text for UI display
                });

                // Update watcher state to prevent re-playing what we just streamed
                // The agent might have saved a file to /tmp/openclaw during its run
                lastPlayedTime = Date.now();
                lastPlayedFile = `stream-${Date.now()}`;

                // Background: Still save to file for history/archival if desired, but don't wait for it
                const ttsDir = '/tmp/openclaw/tts-dashboard';
                if (!fs.existsSync(ttsDir)) fs.mkdirSync(ttsDir, { recursive: true });
                const fileName = `voice-${Date.now()}.mp3`;
                const filePath = `${ttsDir}/${fileName}`;
                generateTTSWithFallback(cleanText, filePath, ttsEngine, voiceId);
            }
            
            res.json({ success: true, response: responseData, text: agentText });
        } catch (e) {
            console.error(`[OpenClaw] Error parsing response: ${e.message}`);
            res.json({ success: true, textResponse: stdout }); // Fallback
        }
    });
});

